import { chromium } from 'playwright';
import { spawn } from 'node:child_process';
import { mkdirSync, writeFileSync } from 'node:fs';
import assert from 'node:assert/strict';

const base=process.env.VITE_BASE_PATH || '/tepeeya.github.io/';
const url=`http://127.0.0.1:4173${base}`;
const server=spawn(process.execPath,['node_modules/vite/bin/vite.js','preview','--host','127.0.0.1','--port','4173','--strictPort'],{stdio:'pipe'});
let browser;
const results=[];
const errors=[];
const record=(name)=>{results.push(name);console.log(`PASS ${name}`);};
mkdirSync('test-results',{recursive:true});
try {
  let ready=false;
  for(let i=0;i<40;i++){try{const response=await fetch(url);if(response.ok){ready=true;break;}}catch{} await new Promise(r=>setTimeout(r,250));}
  assert.ok(ready,'Preview must respond');
  browser=await chromium.launch({headless:true,...(process.env.CHROME_PATH?{executablePath:process.env.CHROME_PATH}:{})});
  const page=await browser.newPage({viewport:{width:1440,height:1000}});
  page.on('pageerror',e=>errors.push(e.message));
  const requested=[];page.on('request',r=>{if(r.url().endsWith('.mp4'))requested.push(r.url());});
  await page.goto(url,{waitUntil:'networkidle'});
  await page.waitForTimeout(1500);
  assert.ok(requested.some(u=>u.endsWith('/hero.mp4')));
  assert.ok(requested.every(u=>u.endsWith('/hero.mp4')));
  record('Only hero video requested on initial load');
  assert.equal(await page.locator('header').innerText().then(t=>/craft/i.test(t)),false);
  assert.ok(await page.locator('header img[alt="TEPEEYA Tepache"]').isVisible());
  assert.equal(await page.locator('.hero-copy .brand-tagline').innerText(),'Un Fermento Mexicano');
  assert.equal(await page.evaluate(()=>document.fonts.check('20px Satisfy')),true);
  record('Supplied brand wordmark and script tagline render; header has no craft text');
  await page.screenshot({path:'test-results/desktop-hero.png'});
  await page.getByRole('button',{name:'Pause TEPEEYA bottle reveal'}).click();
  assert.equal(await page.locator('.hero video').evaluate(v=>v.paused),true);
  record('Hero playback control pauses the film');
  for(const id of ['origins','experience']) {
    await page.evaluate(id=>{const el=document.getElementById(id);window.scrollTo({top:el.offsetTop+innerHeight*.55,behavior:'instant'});},id);
    const video=page.locator(`#${id} video`);
    await video.evaluate(v=>new Promise((resolve,reject)=>{if(v.readyState>=1)return resolve();v.addEventListener('loadedmetadata',resolve,{once:true});setTimeout(()=>reject(new Error('metadata timeout')),10000);}));
    await page.waitForTimeout(500);
    const first=await video.evaluate(v=>v.currentTime);
    await page.evaluate(()=>window.scrollBy({top:350,behavior:'instant'}));
    await page.waitForTimeout(700);
    const second=await video.evaluate(v=>v.currentTime);
    assert.ok(second>first+.3,`${id} video should advance with scroll: ${first} -> ${second}`);
    await page.evaluate(id=>window.scrollTo({top:document.getElementById(id).offsetTop+250,behavior:'instant'}),id);
    await page.waitForTimeout(700);
    assert.ok((await video.evaluate(v=>v.currentTime))<second-.3,`${id} video should reverse with scroll`);
    await page.screenshot({path:`test-results/desktop-${id}.png`});
    record(`${id} film advances with desktop scroll`);
  }
  await page.locator('#flavours').evaluate(el=>window.scrollTo({top:el.offsetTop,behavior:'instant'}));
  await page.waitForTimeout(1000);
  for(const name of ['Mango','Spicy','OG','Honey','Classic']) {
    const button=page.getByRole('button',{name:new RegExp(`\\d.*${name}`)});
    await button.click();
    assert.equal(await button.getAttribute('aria-pressed'),'true');
    assert.ok((await page.locator('#flavour-details h3').innerText()).startsWith(name));
    const modal=page.getByRole('dialog');
    assert.ok(await modal.isVisible());
    assert.equal(await modal.locator('h2').innerText(),name);
    const ingredients=await modal.locator('.dialog-section').first().innerText();
    if(name==='Mango')assert.ok(ingredients.includes('Mango'));
    if(name==='Spicy')assert.ok(ingredients.includes('Ginger')&&ingredients.includes('Green chilli'));
    if(name==='OG')assert.ok(ingredients.includes('Brown cane sugar')&&!ingredients.includes(' · Sugar'));
    if(name==='Honey')assert.ok(ingredients.includes('Honey')&&!ingredients.includes('Sugar'));
    if(name==='Spicy')await page.screenshot({path:'test-results/desktop-flavour-dialog.png'});
    await page.keyboard.press('Escape');
    assert.equal(await modal.isVisible(),false);
    assert.equal(await button.evaluate(el=>el===document.activeElement),true);
  }
  record('All five flavour selections update the live detail panel');
  record('Every flavour opens its confirmed ingredient details; Escape closes and returns focus');
  await page.waitForTimeout(500);
  await page.screenshot({path:'test-results/desktop-flavours.png'});
  await page.getByRole('button',{name:/02.*Mango/}).focus();await page.keyboard.press('Enter');
  assert.ok((await page.locator('#flavour-details h3').innerText()).startsWith('Mango'));
  await page.keyboard.press('Tab');
  assert.equal(await page.getByRole('dialog').evaluate(el=>el.contains(document.activeElement)),true);
  await page.getByRole('button',{name:'Close flavour details'}).click();
  record('Flavour selection supports keyboard activation');
  for(const width of [320,390,768,1024,1440]) {
    await page.setViewportSize({width,height:900});
    assert.equal(await page.evaluate(()=>document.documentElement.scrollWidth>innerWidth),false,`overflow at ${width}`);
    assert.ok(await page.locator('h1').evaluate(el=>el.scrollWidth<=el.clientWidth+1),`headline clipping at ${width}`);
  }
  record('No page overflow or clipped hero headline at 320, 390, 768, 1024, 1440 pixels');
  await page.setViewportSize({width:390,height:844});
  await page.goto(url,{waitUntil:'networkidle'});await page.waitForTimeout(1500);
  assert.ok((await page.locator('.hero video').getAttribute('src')).endsWith('hero-mobile.mp4'));
  await page.screenshot({path:'test-results/mobile-hero.png'});
  for(const selector of ['.hero','#origins','#experience']) {
    await page.locator(selector).evaluate(el=>el.scrollIntoView({behavior:'instant',block:'start'}));
    const video=page.locator(`${selector} video`);
    await page.waitForFunction(selector=>{const v=document.querySelector(`${selector} video`);return v.readyState>=2&&!v.paused&&v.videoWidth>0;},selector);
    const before=await video.evaluate(v=>v.currentTime);
    await page.waitForTimeout(1000);
    const after=await video.evaluate(v=>v.currentTime);
    assert.ok(Math.abs(after-before)>.2,`${selector} should play actual frames on mobile`);
    assert.ok((await video.getAttribute('src')).endsWith('-mobile.mp4'));
    await page.locator(`${selector} .film-control`).click();
    const pausedAt=await video.evaluate(v=>v.currentTime);
    await page.waitForTimeout(350);
    assert.ok(Math.abs((await video.evaluate(v=>v.currentTime))-pausedAt)<.1);
    await page.locator(`${selector} .film-control`).click();
    await page.waitForFunction(selector=>!document.querySelector(`${selector} video`).paused,selector);
    await page.screenshot({path:`test-results/mobile-video-${selector.replace(/[.#]/g,'')}.png`});
  }
  record('All three mobile films decode, play advancing frames, pause and resume on demand');
  await page.evaluate(()=>window.scrollTo({top:0,behavior:'instant'}));
  await page.waitForTimeout(400);
  await page.setViewportSize({width:1440,height:1000});
  await page.waitForFunction(()=>{const v=document.querySelector('.hero video');return v.src.endsWith('/hero.mp4')&&!v.paused&&v.readyState>=2;});
  record('Hero resumes correctly when switching mobile/desktop renditions');
  await page.setViewportSize({width:390,height:844});
  await page.getByRole('button',{name:'Menu +'}).click();
  await page.getByRole('navigation').getByRole('link',{name:/Discover flavours/}).click();
  assert.equal(await page.getByRole('button',{name:'Menu +'}).getAttribute('aria-expanded'),'false');
  await page.waitForTimeout(1500);
  await page.screenshot({path:'test-results/mobile-flavours.png'});
  await page.getByRole('button',{name:/05.*Honey/}).click();
  const bounds=await page.getByRole('dialog').boundingBox();
  assert.ok(bounds.width<=390&&bounds.x>=0);
  assert.equal(await page.evaluate(()=>document.body.style.overflow),'hidden');
  await page.screenshot({path:'test-results/mobile-flavour-dialog.png'});
  await page.getByRole('button',{name:'Close flavour details'}).click();
  await page.waitForFunction(()=>document.body.style.overflow!=='hidden');
  assert.notEqual(await page.evaluate(()=>document.body.style.overflow),'hidden');
  record('Mobile rendition and navigation work');
  const reduced=await browser.newPage({viewport:{width:390,height:844},reducedMotion:'reduce'});
  await reduced.goto(url,{waitUntil:'networkidle'});
  assert.deepEqual(await reduced.locator('video').evaluateAll(v=>v.map(el=>el.getAttribute('src'))),[null,null,null]);
  assert.equal(await reduced.locator('.chapter-stage').first().evaluate(el=>getComputedStyle(el).position),'relative');
  await reduced.getByRole('button',{name:'Play TEPEEYA bottle reveal'}).click();
  await reduced.waitForTimeout(1500);
  assert.equal(await reduced.locator('.hero video').evaluate(v=>v.paused),false);
  record('Reduced motion starts with posters, no video downloads or sticky scenes; explicit playback works');
  const blocked=await browser.newPage();
  await blocked.route('**/*.mp4',route=>route.abort());
  await blocked.goto(url,{waitUntil:'networkidle'});await blocked.waitForTimeout(1000);
  assert.ok(await blocked.locator('.hero video').getAttribute('poster'));
  assert.ok(await blocked.getByRole('heading',{name:'A Tropical Tradition. Reimagined.'}).isVisible());
  record('Blocked video requests retain poster and usable hero content');
  assert.deepEqual(errors,[]);record('No browser runtime errors');
  writeFileSync('test-results/results.json',JSON.stringify({results,errors},null,2));
} finally {await browser?.close();server.kill();}
